              {Object.keys(m.cmds).length > 4 ? "  …" : ""}
            </div>
          </div>
          <Button variant="primary" onclick={() => saveMode(m.name, m.cmds)}>
            <Save size={14} />
            Generovat
          </Button>
        </div>
      </Card>
    {/each}
  </div>

  {#if saveStatus}
    <div class="mt-3 text-xs text-zh-text-muted">{saveStatus}</div>
  {/if}
</div>
