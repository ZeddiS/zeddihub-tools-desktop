    },
  ];

  let saveStatus = $state("");

  async function saveMode(name: string, cmds: Record<string, string>) {
    saveStatus = "";
    const safe = name.toLowerCase().replace(/ /g, "_").replace(/[()]/g, "");
    let content = `// CS2 Gamemode: ${name}\n// Generated by ZeddiHub Tools\n\n`;
    for (const [k, v] of Object.entries(cmds)) {
      content += `${k} ${v}\n`;
    }
    content += `\necho "[ZeddiHub] Gamemode ${name} loaded!"\n`;
    try {
      const path = await saveCfgFile(content, {
        defaultName: `cs2_gamemode_${safe}.cfg`,
        title: `Uložit ${name}`,
      });
      if (path) saveStatus = `✓ Uloženo: ${path}`;
    } catch (e: any) {
      saveStatus = `✗ ${e?.message ?? e}`;
    }
  }
</script>

<div>
  <h3 class="text-lg font-bold text-zh-primary mb-1">CS2 — Gamemode Presety</h3>
  <p class="text-xs text-zh-text-muted mb-4">7 přednastavených módů — klik na „Generovat" uloží příslušný cfg.</p>

